import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
const base = process.env.BASE_URL || 'http://localhost:4173';
const out = process.env.VERIFICATION_OUT || 'docs/cinematic-verification';
await fs.mkdir(out, { recursive: true });
const results = [], errors = [];
for (const width of [1440, 768, 390]) {
  const page = await browser.newPage({ viewport: { width, height: width === 390 ? 844 : 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.locator('#home-title').waitFor();
  await page.waitForTimeout(1500);
  assert.equal(await page.locator('h1').count(), 1);
  assert.equal(await page.locator('.cinema-chapter').count(), 5);
  assert.equal(await page.locator('.cinema-chapter video[src]').count(), 0, 'Unseen chapters must not load videos');
  await page.screenshot({ path: `${out}/hero-${width}.png` });
  const hero = page.locator('.cinema-hero .ambient-video');
  await hero.locator('button').focus();
  await page.keyboard.press('Enter');
  assert.equal(await hero.locator('video').evaluate(v => v.paused), true);
  await page.getByRole('link', { name: 'Descubrir Rosita' }).click();
  await page.waitForTimeout(1000);
  assert(await page.evaluate(() => scrollY > 100));
  for (const id of ['bebidas', 'snacks', 'cuidado', 'ideas', 'ferreteria']) {
    const chapter = page.locator(`#${id}`);
    await chapter.locator('.cinema-chapter-window').scrollIntoViewIfNeeded();
    await page.waitForTimeout(1200);
    assert.equal(await page.locator('video').evaluateAll(videos => videos.filter(v => !v.paused).length) <= 1, true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `${out}/${id}-${width}.png` });
    const destination = await chapter.locator('a').getAttribute('href');
    assert.match(destination, /^\/categoria\//);
  }
  await page.locator('#bebidas .cinema-chapter-window').scrollIntoViewIfNeeded();
  await page.locator('#bebidas button', { hasText: 'Inka Kola' }).click();
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#bebidas button[aria-pressed="true"]').innerText(), 'Inka Kola');
  assert.match(await page.locator('#bebidas video').getAttribute('src'), /inka-cola/);
  await page.locator('.home-featured-section').scrollIntoViewIfNeeded();
  const add = page.locator('.home-product-slide').first().getByRole('button', { name: /Agregar al carrito:/ });
  await add.click();
  await page.getByRole('button', { name: /Abrir carrito, 1 unidad/ }).waitFor();
  await page.locator('.home-product-slide').first().getByRole('link').first().click();
  await page.waitForURL(/producto/);
  await page.goto(base);
  await page.getByRole('link', { name: /Explorar productos/ }).first().click();
  await page.waitForURL(/catalogo/);
  results.push(`${width}: no overflow; five chapters; deferred sources; at most one active video; film selection; product and catalogue routes; add to cart`);
  await page.close();
}
const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
await reduced.goto(base);
await reduced.locator('#home-title').waitFor();
await reduced.waitForTimeout(700);
assert.equal(await reduced.locator('video[src]').count(), 0);
await reduced.locator('#bebidas .cinema-chapter-window').scrollIntoViewIfNeeded();
await reduced.waitForTimeout(700);
assert.equal(await reduced.locator('video[src]').count(), 0);
assert.equal(await reduced.locator('#bebidas .cinema-chapter-film').evaluate(el => getComputedStyle(el).transform), 'none');
await reduced.screenshot({ path: `${out}/reduced-motion.png` });
results.push('Reduced motion: posters, no automatic sources or parallax');
await reduced.close();
const limited = await browser.newPage();
await limited.addInitScript(() => Object.defineProperty(navigator, 'connection', { configurable: true, value: { saveData: true, effectiveType: '4g' } }));
await limited.goto(base);
await limited.locator('#home-title').waitFor();
await limited.waitForTimeout(700);
assert.equal(await limited.locator('video[src]').count(), 0);
await limited.locator('.cinema-hero .video-control').click();
await limited.waitForTimeout(500);
assert.equal(await limited.locator('.cinema-hero video[src]').count(), 1);
results.push('Save-Data: no automatic source; explicit playback available');
await limited.close();
const failure = await browser.newPage();
await failure.route('**/cinematic/*.mp4', route => route.abort());
await failure.goto(base);
await failure.locator('.cinema-hero [data-state="failed"]').waitFor();
assert(await failure.locator('.cinema-hero img').isVisible());
assert(await failure.getByRole('link', { name: 'Explorar productos', exact: true }).first().isVisible());
results.push('Failed video: visible poster, text, CTA and status');
await failure.close();
assert.deepEqual(errors, []);
await fs.writeFile(`${out}/results.json`, JSON.stringify({ results, errors }, null, 2));
console.log(results);
await browser.close();
